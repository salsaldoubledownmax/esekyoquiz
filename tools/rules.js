// stage.js 단서 11개와 같은 순서로, 단서 문장의 뜻을 코드로 적음 (tools/solve.js가 씀)
// 열: 0 장소 1(운동장), 1 장소 2(솔빛채), 2 장소 3(학생자치회실), 3 장소 4(꿈드리 도서관)
// 행: 0 크기, 1 볼 수 있는 것, 2 행사, 3 기억할 해
// s[행][열] = 값, col(s, 행, 값) = 그 값이 있는 열
const rank = (s, c) => Number(s[0][c][0]); // "2등" → 2
module.exports = [
  (s) => s[0][1] === "2등" && s[3][1] === "2018",                    // 1 장소 2는 2018년 체육관, 크기 2등
  (s, col) => col(s, 3, "1997") === col(s, 0, "1등"),                 // 2 1997인 곳은 크기 1등
  (s) => rank(s, 2) > rank(s, 3),                                       // 3 장소 3은 장소 4보다 작음
  (s) => s[1][0] === "학교기",                                          // 4 장소 1에 학교기
  (s, col) => col(s, 1, "학교기") === col(s, 3, "1997"),              // 5 학교기 있는 곳은 1997
  (s, col) => col(s, 1, "의장봉") === col(s, 0, "4등"),                // 6 의장봉은 크기 4등인 곳
  (s, col) => col(s, 2, "발표회") === col(s, 1, "피구공"),            // 7 피구공 있는 곳에서 발표회
  (s, col) => col(s, 2, "학생 회의") === col(s, 1, "의장봉"),         // 8 의장봉 있는 곳에서 학생 회의
  (s) => s[3][2] === "2026",                                            // 9 장소 3은 2026
  (s, col) => col(s, 2, "아침 뽐내기") !== col(s, 1, "책"),            // 10 아침 뽐내기는 책 있는 곳이 아님
  () => true,                                                           // 11 꿈드리 도서관 2013 (장소를 가리키지 않는 정보 단서)
];
